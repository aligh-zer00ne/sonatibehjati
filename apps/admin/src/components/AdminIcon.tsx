export type AdminIconName = keyof typeof icons;
export default function AdminIcon({
  name,
  width,
  height,
  size = 22,
  ...props
}: LucideProps & { name: AdminIconName }) {
  const Icon = icons[name];
  return (
    <Icon
      aria-hidden="true"
      focusable="false"
      size={size}
      width={width ?? height ?? size}
      height={height ?? width ?? size}
      strokeWidth={2}
      {...props}
    />
  );
}
